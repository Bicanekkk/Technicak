package org.example;

public class Ridic {
    private String Prijmeni;
    private int rok_narozeni;

    public Ridic(String prijmeni, int rok_narozeni) {
        Prijmeni = prijmeni;
        this.rok_narozeni = rok_narozeni;
    }


        public String getPrijmeni() {
            return Prijmeni;
        }

        public int getRok_narozeni() {
            return rok_narozeni;
        }
}

